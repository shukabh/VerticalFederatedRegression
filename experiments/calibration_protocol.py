"""
calibration_protocol.py -- calibration of the full protocol: two releases, the tight zCDP
conversion, and the ridge chosen from the first release.

A run spends (eps, delta) on two releases (a third, for y'y, only when y'y is not free):
  stage 1   releases the O-dependent Gram blocks (triu B, C), sensitivity Delta_G, zCDP share f1;
  stage 2   releases every entry, sensitivity Delta, with the rest of the budget.

  rho_run   largest rho whose zCDP guarantee implies (eps, delta), by the tight conversion of
            Canonne, Kamath and Steinke (2020):
              inf_{a>1} exp((a-1)(a rho - eps)) / (a-1) * (1 - 1/a)^a <= delta
            The simple bound sqrt(rho) >= sqrt(L + eps) - sqrt(L), L = ln(1/delta), is slightly
            conservative and gives the closed-form planning formula below.
  sigma     sigma_1 = Delta_G / sqrt(2 f1 rho_run),  sigma_2 = Delta / sqrt(2 (1 - f1) rho_run)
  ridge     lambda <= lambda_I = max{0, g* + r_1 - lambda_min(G_1)},  g* = 2 theta* sigma_2 sqrt(p),
            r_1 = sigma_1 (2 sqrt(p) + 2 sqrt(ln(1/alpha_L))).  For planning, lambda_min(G_1) ~ n ell
            (ell: smallest eigenvalue of G/n, from public reference data), so the ridge is off once
            n >= (g* + r_1) / ell.

The flooding noise adds n_rel (delta_B + 2^-kappa) ~ 2e-12 to delta and is ignored here. The script
also compares sigma_2 with the single-release analytic-Gaussian sigma that the accuracy experiments
(reports/coef_accuracy, reports/adassp) simulate.
Usage: python experiments/calibration_protocol.py > reports/calibration/protocol.md
"""
from __future__ import annotations

import os
import sys

import numpy as np
from scipy.optimize import brentq, minimize_scalar

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim_core as sc  # noqa: E402

F1, THETA_STAR, ALPHA_L = 0.1, 2.5, 0.0025
EPS = [0.1, 0.25, 0.5, 1, 2, 4, 8]


def log_delta_cks(rho, eps):
    """log of the Canonne-Kamath-Steinke delta for rho-zCDP at eps (minimised over the order a)."""
    f = lambda t: ((a := 1 + np.exp(t)) - 1) * (a * rho - eps) - np.log(a - 1) + a * np.log1p(-1 / a)
    return minimize_scalar(f, bounds=(-15, 15), method="bounded", options={"xatol": 1e-10}).fun


def rho_tight(eps, delta):
    return brentq(lambda r: log_delta_cks(r, eps) - np.log(delta), 1e-12, 50 * eps, xtol=1e-14)


def rho_simple(eps, delta):
    L = np.log(1 / delta)
    return (np.sqrt(L + eps) - np.sqrt(L)) ** 2


def run(eps, delta, Delta, Delta_G, p, f1=F1):
    rho = rho_tight(eps, delta)
    s1, s2 = Delta_G / np.sqrt(2 * f1 * rho), Delta / np.sqrt(2 * (1 - f1) * rho)
    r1 = s1 * (2 * np.sqrt(p) + 2 * np.sqrt(np.log(1 / ALPHA_L)))
    return dict(rho=rho, s1=s1, s2=s2, r1=r1, g=2 * THETA_STAR * s2 * np.sqrt(p))


def g3(v):
    return f"{v:.3g}"


def nfmt(v):
    return f"{v:.0f}" if v < 1000 else f"{v / 1000:.1f}k" if v < 10000 else f"{v / 1000:.0f}k"


def main():
    print("# Calibration of the full protocol\n")
    print(f"Two releases per run (y'y free); stage-1 share f1 = {F1}; theta* = {THETA_STAR}; "
          f"alpha_L = {ALPHA_L}. Generated by experiments/calibration_protocol.py.\n")

    print("## 1. Stage-2 noise sigma_2 / Delta\n")
    print("| delta \\ eps | " + " | ".join(f"{e:g}" for e in EPS) + " |")
    print("|---" * (len(EPS) + 1) + "|")
    for d in [1e-6, 1e-8, 1e-9]:
        print(f"| {d:.0e} | " + " | ".join(g3(run(e, d, 1.0, 1.0, 11)["s2"]) for e in EPS) + " |")

    print("\n## 2. Planning formula: sigma_2 <= Delta / (sqrt(2 (1 - f1)) (sqrt(L + eps) - sqrt(L)))\n")
    rat = [np.sqrt(rho_tight(e, d) / rho_simple(e, d)) for e in EPS for d in [1e-6, 1e-8, 1e-9]]
    print(f"Closed form / exact, eps in [{EPS[0]}, {EPS[-1]}], delta in [1e-9, 1e-6]: "
          f"{min(rat):.3f} to {max(rat):.3f}\n")

    print("## 3. Protocol sigma_2 / single-release analytic-Gaussian sigma (what the experiments simulate)\n")
    print("| delta \\ eps | " + " | ".join(f"{e:g}" for e in EPS) + " |")
    print("|---" * (len(EPS) + 1) + "|")
    for d in [1e-5, 1e-6]:
        print(f"| {d:.0e} | " + " | ".join(f"{run(e, d, 1.0, 1.0, 11)['s2'] / sc.analytic_gauss_sigma(1.0, e, d):.2f}"
                                           for e in EPS) + " |")

    B_R, B_O, B_y, p, ell, n = 5.59, 6.24, 2.89, 11, 0.494, 10_000
    Delta, Delta_G = sc.delta_rep(B_R, B_O, B_y), sc.delta_rep(B_R, B_O, 0.0)
    print(f"\n## 4. Worked example: simulation population, delta = 1e-9\n")
    print(f"B_R = {B_R}, B_O = {B_O}, B_y = {B_y}, p = {p}, ell = {ell}: Delta = {Delta:.2f}, Delta_G = {Delta_G:.2f}\n")
    print("| eps | rho_run | sigma_1 | sigma_2 | r_1 | lambda at n = 10k | ridge off from n | one release, fixed ridge: off from n |")
    print("|---|---|---|---|---|---|---|---|")
    for e in [0.5, 1, 2, 4, 8]:
        r = run(e, 1e-9, Delta, Delta_G, p)
        s_ag = sc.analytic_gauss_sigma(Delta, e, 1e-9)
        print(f"| {e:g} | {r['rho']:.4f} | {r['s1']:.0f} | {r['s2']:.0f} | {r['r1']:.0f} | "
              f"{max(0.0, r['g'] + r['r1'] - n * ell):.0f} | {nfmt((r['g'] + r['r1']) / ell)} | "
              f"{nfmt(2 * THETA_STAR * s_ag * np.sqrt(p) / ell)} |")

    print("\n## 5. What each choice does to sigma_2 (delta = 1e-9 unless stated)\n")
    s = lambda e, d=1e-9, f1=F1: run(e, d, 1.0, 1.0, p, f1)["s2"]
    dbl = [s(2 * e) / s(e) for e in [0.25, 0.5, 1, 2, 4]]
    dlt = [s(e, 1e-9) / s(e, 1e-6) for e in [0.25, 0.5, 1, 2, 4, 8]]
    f2 = [s(e, f1=0.2) / s(e) for e in [0.5, 1, 4]]
    kk = [run(e / 5, 1e-9 / 5, 1.0, 1.0, p)["s2"] / s(e) for e in [0.5, 1, 4]]   # basic split over 5 runs
    kz = [1 / np.sqrt(rho_tight(e, 1e-9) / 5 / rho_tight(e, 1e-9)) for e in [1]]
    split = sc.delta_rep(np.sqrt(.5), np.sqrt(.5), 1.0) / sc.delta_rep(1, 1, 1)
    rows = [("bounds 2x closer to the data (no extra clipping)", [0.25]),
            ("split a unit row bound (B_R^2 = B_O^2 = 1/2 instead of B_R = B_O = 1)", [split]),
            ("double eps (eps in [0.25, 4])", dbl),
            ("delta from 1e-6 to 1e-9", dlt),
            ("stage-1 share 0.2 instead of 0.1", f2),
            ("one budget shared by 5 runs (zCDP: rho / 5)", kz),
            ("one budget shared by 5 runs (split eps and delta)", kk)]
    rng = lambda v, k=1: f"{min(v) ** k:.2f}" if np.ptp(v) < 5e-3 else f"{min(v) ** k:.2f} to {max(v) ** k:.2f}"
    print("Records needed scale like sigma_2 for prediction and like sigma_2^2 for coefficients "
          "(experiments/calibration_heuristic.py).\n")
    print("| change | sigma_2 | records for prediction | records for coefficients |\n|---|---|---|---|")
    for name, v in rows:
        print(f"| {name} | {rng(v)} | {rng(v)} | {rng(v, 2)} |")


if __name__ == "__main__":
    main()
