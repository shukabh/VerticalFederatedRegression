"""Key numbers and LaTeX rows of the follow-up checks, from reports/v31_more/*.json.

    python experiments/v31_more/tables_more.py

Writes reports/v31_more/key_numbers.md and reports/v31_more/latex_rows.tex.
"""
from __future__ import annotations

import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mcommon as mc  # noqa: E402


def load(name):
    p = os.path.join(mc.REPORT, name)
    return json.load(open(p)) if os.path.exists(p) else None


def f3(x):
    return f'{x:.3f}'


def ci(c, key='clustered', d=3):
    return f'{c[key][0]:.{d}f}--{c[key][1]:.{d}f}'


def nfmt(n):
    return f'{n:,}'.replace(',', '{,}')


def main():
    L, T = ['# Key numbers (generated by experiments/v31_more/tables_more.py)', ''], []
    # ---- item 27
    d = load('coverage_real.json')
    if d:
        L += ['## #27 Real data, setting I, calibrated noise (delta = 1e-9), fixed data, block normalization', '',
              '| dataset | n | eps | ridge on | coverage (all coef.) | clustered 95% CI | per-coef. range | median half-width (slopes) | refused |',
              '|---|---|---|---|---|---|---|---|---|']
        for c in d['cells']:
            cv = c['coverage_all']
            L.append(f"| {c['dataset']} | {c['n']:,} | {c['eps']:g} | {c['ridge_on']:.2f} | {cv['coverage']:.4f} ({cv['covered']}/{cv['total']}) | "
                     f"{ci(cv)} | {cv['per_coef_min']:.3f}-{cv['per_coef_max']:.3f} | {c['half_theta_median']:.3g} | {c['refused']:.3f} |")
        o = d['overall']
        L += ['', f"Overall: {o['cells']} cells, pooled coverage {o['coverage_range'][0]:.4f}-{o['coverage_range'][1]:.4f}; "
              f"per-coefficient {o['per_coef_min']:.3f}-{o['per_coef_max']:.3f}; CI below target: {o['cells_ci_excludes_target_below']}; "
              f"CI above target: {len(o['cells_ci_excludes_target_above'])} cells; ridge-off cells: {o['ridge_off_cells']}", '']
        L += ['Bias-aware interval vs the full-data least-squares fit (descriptive; conditional on one sample):', '']
        for c in d['cells']:
            if c['beta_meaningful']:
                ba = c['bias_aware']
                L.append(f"- {c['dataset']} n={c['n']:,} eps={c['eps']:g}: all finite {ba['all_finite_share']}, coverage of beta_pop {ba['coverage_beta_pop']:.3f}; "
                         f"max |beta_hat - beta_pop| = {c['beta_hat_minus_beta_pop_max']:.3g}")
        L.append('')
        # LaTeX rows: one row per dataset and n, three eps columns
        T.append('% real-data coverage table rows: dataset & n & ridge & eps=1 & eps=4 & eps=8')
        seen = []
        for c in d['cells']:
            key = (c['dataset'], c['n'])
            if key in seen:
                continue
            seen.append(key)
            row = [x for x in d['cells'] if (x['dataset'], x['n']) == key]
            ridge = 'on' if all(x['ridge_on'] == 1 for x in row) else 'off' if all(x['ridge_on'] == 0 for x in row) else \
                '/'.join('on' if x['ridge_on'] == 1 else 'off' if x['ridge_on'] == 0 else f"{x['ridge_on']:.2f}" for x in row)
            cells = ' & '.join(f"${x['coverage_all']['coverage']:.3f}$ ({ci(x['coverage_all'])})" for x in sorted(row, key=lambda x: x['eps']))
            T.append(f"    {c['dataset']} & {nfmt(c['n'])} & {ridge} & {cells} \\\\")
    # ---- item 30
    d = load('coverage_repeat.json')
    if d:
        L += ['## #30 Coverage repeat at the earlier encrypted settings (previous setting), 10,000 plaintext releases each', '',
              '| data | eps | kappa | plaintext coverage | clustered 95% CI | per-coef. | z sd | encrypted | Wilson CI | P(batch <= encrypted) |',
              '|---|---|---|---|---|---|---|---|---|---|']
        tot_e, tot_n, mu, var = 0, 0, 0.0, 0.0
        for r in d['results']:
            c, e = r['coverage'], r['encrypted']
            L.append(f"| {r['tag']} | {r['eps']:g} | {r['kappa']} | {c['coverage']:.4f} | {ci(c, d=4)} | {c['per_coef_min']:.3f}-{c['per_coef_max']:.3f} | "
                     f"{r['z']['sd']:.3f} | {e['covered']}/{e['total']} ({e['coverage']:.3f}) | {e['wilson'][0]:.3f}-{e['wilson'][1]:.3f} | {e['p_batch_le_observed']:.3f} |")
            tot_e += e['covered']
            tot_n += e['total']
            mu += e['total'] * c['coverage']
            var += e['total'] * c['coverage'] * (1 - c['coverage']) * (c['design_effect'] or 1)
        from scipy import stats
        L += ['', f"All earlier encrypted runs pooled: {tot_e}/{tot_n} = {tot_e / tot_n:.4f}; expected from the plaintext coverages "
              f"{mu:.1f} (sd {math.sqrt(var):.1f}, design effects applied): z = {(tot_e - mu) / math.sqrt(var):+.2f}, one-sided p = "
              f"{stats.norm.cdf((tot_e - mu) / math.sqrt(var)):.3f}", '']
    # ---- item 31
    for fn, title in (('encrypted_more_first50.json', 'first 50 runs per configuration (pre-specified)'),
                      ('encrypted_more.json', 'all runs')):
        d = load(fn)
        if not d:
            continue
        L += [f'## #31 Encrypted runs, {title}', '']
        for cfg, r in d['results'].items():
            line = (f"- {cfg} ({r['setting']}, eps = {r['eps']:g}, kappa = {r['kappa']}): {r['runs']} runs at {r['git_heads']}, wall median "
                    f"{r['wall']['median']:.1f} s; ridge on in {r['ridge_on_runs']} runs; lambda median {r['lam']['median']:.0f} "
                    f"(sim 95% {r['sim']['lam_q'][0]:.0f}-{r['sim']['lam_q'][2]:.0f}), in range {r['lam_in_sim_95']}; theta in sim 95% "
                    f"{r['theta_in_sim_95']} ({r['theta_in_sim_95_frac']:.3f}, Wilson {r['theta_in_sim_95_wilson'][0]:.3f}-{r['theta_in_sim_95_wilson'][1]:.3f}); "
                    f"z given lambda sd {r['z_given_lambda']['sd']:.3f}, max {r['z_given_lambda']['max_abs']:.2f}; refused {r['refused']}; A exact {r['A_exact']}; "
                    f"reproduced from the decrypted noise to {max(r['reproduced_from_decrypted_noise'].values()):.1e}")
            if 'coverage' in r:
                c = r['coverage']
                line += f"; Wald coverage {c['covered']}/{c['total']} = {c['coverage']:.4f} (clustered {ci(c, d=4)}, Wilson {ci(c, 'wilson', 4)})"
            L.append(line)
            for s in ('stage1', 'stage2_with_yy'):
                t = r['noise'][s]
                L.append(f"    - noise {s}: {t['entries']} entries, mean {t['mean']:+.4f} (SE {t['se_entry']:.4f}, z {t['z']:+.2f}, run-level p {t['run_p']:.3f}), "
                         f"sd {t['sd']:.4f}, KS p {t['ks_p']:.3f}, max |z| {t['max_abs']:.2f}")
            for s, t in r['noise_all_slots'].items():
                L.append(f"    - all slots, release {s}: {t['values']:,} values, mean {t['mean']:+.5f} (SE {t['se']:.5f}), sd {t['sd']:.5f}, "
                         f"run-level p {t['run_mean_t_p']:.3f}, max |z| {t['max_abs']:.2f}")
        L.append('')
        for k in ('stage1', 'stage2'):
            t = d['noise_pooled'][k]
            L.append(f"- pooled new runs {k}: {t['entries']} entries, mean {t['mean']:+.4f} (SE {t['se_entry']:.4f}, z {t['z']:+.2f}, "
                     f"p {t['p_entry']:.3f}; run-level p {t['run_p']:.3f}), sd {t['sd']:.4f}, KS p {t['ks_p']:.3f} (KS stat {t['ks_stat']:.4f})")
        if 'I2_with_replication' in d:
            c = d['I2_with_replication']['coverage']
            L.append(f"- I2 and I2r pooled: {d['I2_with_replication']['runs']} runs, Wald coverage {c['covered']}/{c['total']} = {c['coverage']:.4f} "
                     f"(clustered {ci(c, d=4)}, Wilson {ci(c, 'wilson', 4)})")
        for k, v in d['noise_pooled'].items():
            if k in ('stage1', 'stage2'):
                continue
            for kk, t in v.items():
                if isinstance(t, dict) and 'mean' in t:
                    L.append(f"- pooled {k} {kk}: {t['entries']} entries, mean {t['mean']:+.4f} (SE {t['se_entry']:.4f}, z {t['z']:+.2f}, "
                             f"p {t['p_entry']:.3f}; run-level p {t['run_p']:.3f}), sd {t['sd']:.4f}, KS p {t['ks_p']:.3f}")
                elif isinstance(t, dict):
                    for k3, t3 in t.items():
                        for k4, t4 in t3.items():
                            L.append(f"- pooled {k} {kk} {k3} {k4}: {t4['entries']} entries, mean {t4['mean']:+.4f} (z {t4['z']:+.2f}, p {t4['p_entry']:.3f}), "
                                     f"sd {t4['sd']:.4f}, KS p {t4['ks_p']:.3f}")
        L.append('')
    d = load('encrypted_plaincov.json')
    if d:
        L += ['Plaintext Wald coverage at the encrypted configurations (10,000 releases):', '']
        for cfg, r in d.items():
            c = r['coverage']
            L.append(f"- {cfg}: {c['coverage']:.4f} (clustered {ci(c, d=4)}), z sd {r['z_sd']:.3f}; 95% range of the covered count in a batch of "
                     f"50 runs {r['batch_totals']['50']['q025']:.0f}-{r['batch_totals']['50']['q975']:.0f} of 550, of 100 runs "
                     f"{r['batch_totals']['100']['q025']:.0f}-{r['batch_totals']['100']['q975']:.0f} of 1,100")
        L.append('')
    # ---- item 34
    d = load('cost_fullrecord.json')
    if d:
        L += ['## #34 Full-record SSP: cryptographic cost relative to v3.1 (cost model, single thread, d_R = 4, d_O = 6, n_R^max = 2,000)', '',
              '| n_bar_O | m | aggregation v3.1 (s) | extra (s) | ratio | O CPU v3.1 | extra | ratio | R CPU v3.1 | extra | comm v3.1 (MB) | extra | ratio | est. wall ratio |',
              '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
        for r in d['rows']:
            v, f, q = r['v31'], r['full_record'], r['ratio']
            L.append(f"| {r['n_bar_O']:,} | {r['m']} | {v['agg']:.1f} | {f['extra_agg']:.2f} | {q['agg']:.3f} (cached ones {q['agg_cached']:.3f}) | "
                     f"{v['cpu_O']:.1f} | {f['extra_cpu_O']:.2f} | {q['cpu_O']:.3f} | {v['cpu_R']:.2f} | {f['extra_cpu_R']:.2f} | {v['comm_MB']:.1f} | "
                     f"{f['extra_comm_MB']:.1f} | {q['comm']:.3f} | {q['wall_single_thread_est']:.3f} |")
        cal = d['calibration']
        L += ['', f"Releases: unchanged (one ciphertext each, {cal['v31']['entries']} -> {cal['full_record']['entries']} packed entries). "
              f"Calibration with the larger entry counts: log2 B_tot {cal['v31']['log2_B_tot']} -> {cal['full_record']['log2_B_tot']}, "
              f"log2 Omega_f {cal['v31']['log2_Omega_f']:.3f} -> {cal['full_record']['log2_Omega_f']:.3f}, kappa {cal['v31']['kappa']} -> "
              f"{cal['full_record']['kappa']}, sigma unchanged.", '']
    open(os.path.join(mc.REPORT, 'key_numbers.md'), 'w').write('\n'.join(L) + '\n')
    open(os.path.join(mc.REPORT, 'latex_rows.tex'), 'w').write('\n'.join(T) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
