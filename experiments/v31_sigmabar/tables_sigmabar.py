"""reports/v31_sigmabar/key_numbers.md from reports/v31_sigmabar/sim_sigmabar.json (written by sim_sigmabar.py).

    python experiments/v31_sigmabar/tables_sigmabar.py
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
REPORT = os.path.join(ROOT, 'reports', 'v31_sigmabar')

LABEL = dict(guaranteed='guaranteed (sigma_bar^2 = B_y^2)', declared='declared (sigma_bar^2 = 0.5)',
             model='working model (s~^2)')


def fmt_half(d):
    if d['finite'] == 0:
        return 'unbounded'
    s = f"{d['median_half']:.4g}"
    return s if d['finite'] == 1 else f"{s} [{100 * d['finite']:.0f}% fin.]"


def fmt_cov(c):
    return f"{c['pooled']:.3f} ({c['min']:.3f}-{c['max']:.3f})"


def main():
    R = json.load(open(os.path.join(REPORT, 'sim_sigmabar.json')))
    L = ['# Key numbers (generated by experiments/v31_sigmabar/tables_sigmabar.py)', '',
         'Setting I, delta = 1e-9, plaintext simulation of the release and solve steps, 1,000 cohorts per cell, '
         'R^2 = 0.5 before clipping. Coverage of the ten slopes: pooled (min-max over slopes); an unbounded interval '
         'counts as covering. Target 0.955 per slope. beta*: projection coefficient G^-1 X~\' E[y~ | X] of each cohort '
         '(the estimand of Proposition S10b); beta_pop: population least-squares coefficient of the clipped data '
         '(4M rows). Median half-width over the finite intervals of the slopes.', '',
         '## Populations', '',
         '| population | B_y | B_y^2 | share of y clipped | mean Var(y~ given X) | max Var(y~ given X) | sigma_2 at eps = 1 / 8 |',
         '|---|---|---|---|---|---|---|']
    for k, p in R['populations'].items():
        L.append(f"| {k} | {p['B_y']:.3f} | {p['B_y2']:.3f} | {p['clip_rate_y']:.3f} | {p['mean_cond_var']:.3f} | "
                 f"{p['max_cond_var']:.3f} | {p['sigma']['1']['sigma2']:.0f} / {p['sigma']['8']['sigma2']:.1f} |")
    L += ['', 'Mean and max over 4M population rows. Var(y~ given X) <= B_y^2 always. For hetero the declared value 0.5 '
          'is not a bound (max 1.87), so the declared interval is not admissible there and is not reported.', '']
    for tgt, title in (('cond', 'beta* (conditional projection coefficient)'), ('pop', 'beta_pop (population coefficient)')):
        L += [f'## Coverage of {title}', '',
              '| population | eps | n | ridge | guaranteed | declared | working model | Wald for theta_lambda |',
              '|---|---|---|---|---|---|---|---|']
        for c in R['cells']:
            dec = fmt_cov(c['declared']['cov_' + tgt]) if c['pop'] != 'hetero' else '(not admissible)'
            L.append(f"| {c['pop']} | {c['eps']:g} | {c['n']:,} | {c['ridge']:.2f} | {fmt_cov(c['guaranteed']['cov_' + tgt])} | "
                     f"{dec} | {fmt_cov(c['model']['cov_' + tgt])} | {c['wald']['pooled']:.3f} |")
        L.append('')
    L += ['## Median half-width (slopes)', '',
          '| population | eps | n | guaranteed | declared | working model | ratio guaranteed / model (median) | Wald | median s~^2 |',
          '|---|---|---|---|---|---|---|---|---|']
    for c in R['cells']:
        dec = fmt_half(c['declared']) if c['pop'] != 'hetero' else '--'
        L.append(f"| {c['pop']} | {c['eps']:g} | {c['n']:,} | {fmt_half(c['guaranteed'])} | {dec} | "
                 f"{fmt_half(c['model'])} | {c['width_ratio_g_over_m']:.2f} | {c['wald']['median_half']:.4g} | "
                 f"{c['s2_median']:.3f} |")
    L.append('')
    # summary lines
    L += ['## Summary', '']
    for pop in R['populations']:
        cells = [c for c in R['cells'] if c['pop'] == pop and c['guaranteed']['finite'] > 0]
        if not cells:
            continue
        for k in ('guaranteed', 'declared', 'model'):
            if pop == 'hetero' and k == 'declared':
                continue
            mins = [c[k]['cov_cond']['min'] for c in cells]
            pooled = [c[k]['cov_cond']['pooled'] for c in cells]
            minsp = [c[k]['cov_pop']['min'] for c in cells]
            L.append(f"* {pop}, {LABEL[k]}: beta* pooled {min(pooled):.3f}-{max(pooled):.3f}, lowest slope "
                     f"{min(mins):.3f}; beta_pop lowest slope {min(minsp):.3f} (cells with a finite interval: {len(cells)})")
    L.append('')
    with open(os.path.join(REPORT, 'key_numbers.md'), 'w') as fh:
        fh.write('\n'.join(L))
    print('wrote', os.path.join(REPORT, 'key_numbers.md'))


if __name__ == '__main__':
    main()
